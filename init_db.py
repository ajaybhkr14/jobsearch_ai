# init_db.py
import psycopg2
import os
from dotenv import load_dotenv

# Load database credentials from the .env file
load_dotenv()

def init_db():
    print("Connecting to PostgreSQL...")
    conn = psycopg2.connect(
        host=os.getenv("DB_HOST", "localhost"),
        port=os.getenv("DB_PORT", "5432"),
        dbname=os.getenv("DB_NAME", "postgres"),
        user=os.getenv("DB_USER", "postgres"),
        password=os.getenv("DB_PASSWORD", "postgres")
    )
    cursor = conn.cursor()

    # 1. Enable the pgvector extension inside PostgreSQL
    # This gives Postgres the ability to understand high-dimensional math
    cursor.execute("CREATE EXTENSION IF NOT EXISTS vector;")

    # 2. Create the table
    # The 'embedding vector(1536)' column will store the array of 1536 numbers generated by OpenAI
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS jobs (
            id SERIAL PRIMARY KEY,
            title VARCHAR(255) NOT NULL,
            company_name VARCHAR(255) NOT NULL,
            salary_min INT,
            salary_max INT,
            is_remote BOOLEAN DEFAULT FALSE,
            required_skills TEXT[],
            raw_markdown TEXT,
            embedding vector(1536),
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        );
    """)

    # 3. Create the HNSW index for lightning-fast searches
    # 'vector_cosine_ops' tells Postgres to index based on Cosine Similarity (measuring the angle between two vectors)
    cursor.execute("""
        CREATE INDEX IF NOT EXISTS jobs_embedding_hnsw_idx 
        ON jobs USING hnsw (embedding vector_cosine_ops);
    """)

    # Save changes and close the connection
    conn.commit()
    cursor.close()
    conn.close()
    print("✅ PostgreSQL initialized with pgvector and HNSW index!")

if __name__ == "__main__":
    init_db()